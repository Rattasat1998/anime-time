// Helper function to get Thai title
export function getThaiTitle(animeId: string, title: string, titleJapanese?: string): string | null {
  const animeTitles = thaiAnimeTitles[animeId];
  if (!animeTitles) return null;
  
  // Try exact match first
  if (animeTitles[title]) {
    return animeTitles[title];
  }
  
  // Try Japanese title match
  if (titleJapanese && animeTitles[titleJapanese]) {
    return animeTitles[titleJapanese];
  }
  
  // Try partial match
  for (const [key, thaiTitle] of Object.entries(animeTitles)) {
    if (title.toLowerCase().includes(key.toLowerCase()) || 
        (titleJapanese && titleJapanese.toLowerCase().includes(key.toLowerCase()))) {
      return thaiTitle;
    }
  }
  
  return null;
}

// Helper function to check if anime has Thai title
export function hasThaiTitle(animeId: string, title: string, titleJapanese?: string): boolean {
  return getThaiTitle(animeId, title, titleJapanese) !== null;
}
